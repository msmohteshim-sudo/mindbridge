// === AI Recommendations Engine (Demo) ===
export function getAIRecommendations(profile: typeof demoCognitiveProfile) {
  const weakest = Object.entries({
    memory: profile.memory,
    attention: profile.attention,
    language: profile.language,
    executiveFunction: profile.executiveFunction,
    visuospatial: profile.visuospatial,
    processingSpeed: profile.processingSpeed,
  })
    .sort(([, a], [, b]) => a - b)
    .slice(0, 2)
    .map(([k]) => k);

  const recommendations: string[] = [];

  if (weakest.includes('executiveFunction') || weakest.includes('processingSpeed')) {
    recommendations.push('sequence-arrangement', 'virtual-shopping', 'daily-routine');
  }
  if (weakest.includes('memory')) {
    recommendations.push('memory-match', 'family-memory', 'object-recognition');
  }
  if (weakest.includes('attention')) {
    recommendations.push('attention-tasks', 'whats-missing', 'coloring-relaxation');
  }
  if (weakest.includes('language')) {
    recommendations.push('language-tasks', 'story-completion', 'music-recognition');
  }

  return [...new Set(recommendations)].slice(0, 4);
}
